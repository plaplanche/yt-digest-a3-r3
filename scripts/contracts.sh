#!/usr/bin/env bash
# Generates TypeScript types and Pydantic v2 models from contracts/*.schema.json.
#   ./scripts/contracts.sh          regenerate worker/src/contracts/ and node/src/yt_digest_node/contracts/
#   ./scripts/contracts.sh --check  regenerate into a temporary directory; exit 1, naming the files, on a difference
set -euo pipefail
cd "$(dirname "$0")/.."

mode="${1:-generate}"
case "$mode" in
  generate | --check) ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

ts_dir=worker/src/contracts
py_dir=node/src/yt_digest_node/contracts
header="Generated by scripts/contracts.sh from contracts/*.schema.json. Do not edit."

(cd node && uv sync --locked --quiet)
[[ -d worker/node_modules ]] || (cd worker && npm ci --silent)

out="$(mktemp -d)"
trap 'rm -rf "$out"' EXIT
mkdir -p "$out/$ts_dir" "$out/$py_dir"
printf '# %s\n' "$header" >"$out/$py_dir/__init__.py"

for schema in contracts/*.schema.json; do
  name="$(basename "$schema" .schema.json)"
  (cd worker && npx --no-install json2ts --input "../$schema" --output "$out/$ts_dir/$name.ts" \
    --bannerComment "/* $header */")
  (cd node && uv run --no-sync datamodel-codegen --input "../$schema" --input-file-type jsonschema \
    --output "$out/$py_dir/${name//-/_}.py" --output-model-type pydantic_v2.BaseModel \
    --target-python-version 3.12 --use-specialized-enum --use-annotated --use-standard-collections \
    --use-union-operator --disable-timestamp --formatters ruff-format --custom-file-header "# $header" \
    --enum-field-as-literal-map '{"level":"literal","service":"literal","status":"literal","source":"literal","event":"enum"}' \
    2>/dev/null)
done

# The runtime list of the catalogue, next to the union type of the event names.
# shellcheck disable=SC2016  # the JavaScript template literals are not shell expansions
node --input-type=module -e '
  import { readFileSync, appendFileSync } from "node:fs";
  const events = JSON.parse(readFileSync(process.argv[1], "utf8")).$defs.LogEventName.enum;
  const list = events.map((e) => `  ${JSON.stringify(e)},\n`).join("");
  appendFileSync(process.argv[2], `\nexport const LOG_EVENTS: readonly LogEventName[] = [\n${list}];\n`);
' contracts/log-event.schema.json "$out/$ts_dir/log-event.ts"

(
  cd node
  uv run --no-sync ruff check --quiet --fix --select I --config pyproject.toml "$out/$py_dir"
  uv run --no-sync ruff format --quiet --config pyproject.toml "$out/$py_dir"
)

if [[ "$mode" == "generate" ]]; then
  rm -rf "$ts_dir" "$py_dir"
  mkdir -p "$ts_dir" "$py_dir"
  cp "$out/$ts_dir"/* "$ts_dir"/
  cp "$out/$py_dir"/* "$py_dir"/
  exit 0
fi

stale=()
for dir in "$ts_dir" "$py_dir"; do
  declare -A seen=()
  for f in "$out/$dir"/* "$dir"/*; do
    [[ -f "$f" ]] && seen["$dir/$(basename "$f")"]=1
  done
  for f in "${!seen[@]}"; do
    cmp -s "$out/$f" "$f" 2>/dev/null || stale+=("$f")
  done
  unset seen
done
if ((${#stale[@]} > 0)); then
  echo "generated files out of date (run ./scripts/contracts.sh):" >&2
  printf '  %s\n' "${stale[@]}" | sort >&2
  exit 1
fi
echo "generated files are up to date"
